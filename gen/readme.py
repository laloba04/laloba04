"""Genera README.md (español) y README.en.md (inglés) con <picture> para móvil."""
import hashlib
import pathlib
import re
from xml.sax.saxutils import escape as esc

ROOT = pathlib.Path(__file__).resolve().parents[1]

MOBILE_QUERY = "(max-width: 600px)"


def readme(cfg, lang, has_stats, stats_alt="", cv=None):
    d = cfg["lang"][lang]
    user, links = cfg["user"], cfg["links"]
    other = "README.en.md" if lang == "es" else "README.md"
    a = f"https://github.com/{user}/{user}/raw/main/assets/{lang}"
    blob = f"https://github.com/{user}/{user}/blob/main"
    b = d["btn"]

    def pic(name, alt):
        return (f'<picture>\n'
                f'  <source media="{MOBILE_QUERY}" srcset="{a}/mobile/{name}">\n'
                f'  <img src="{a}/{name}" width="100%" alt="{esc(alt)}">\n'
                f'</picture>')

    def linked(href, inner):
        return f'<a href="{href}">\n{inner}\n</a>'

    # tarjetas de 412 px sin ancho fijo: dos por fila en PC, una por fila en móvil
    quests = "\n".join(
        f'<a href="{q.get("url", links["portfolio"])}"><img src="{a}/quest-{q["slug"]}.svg" '
        f'alt="{esc(q["name"])} — {esc(q[lang])} ({esc(q["stack"])})"></a>'
        for q in cfg["quests"])

    parts = [
        f'<a href="{blob}/{other}"><img src="{a}/btn-lang.svg" alt="{esc(d["lang_alt"])}"></a>',
        f'**{cfg["name"]}** · {d["tagline"]}',
        pic("hero.svg", d["hero_alt"]),
        "\n".join([
            f'<a href="{links["portfolio"]}"><img src="{a}/btn-portfolio.svg" alt="{b["portfolio"]}"></a>',
            f'<a href="{links["linkedin"]}"><img src="{a}/btn-linkedin.svg" alt="{b["linkedin"]}"></a>',
            f'<a href="mailto:{links["email"]}"><img src="{a}/btn-email.svg" alt="{b["email"]}"></a>',
        ] + ([f'<a href="{cv}"><img src="{a}/btn-cv.svg" alt="{b["cv"]}"></a>'] if cv else [])),
        pic("sheet.svg", d["sheet_alt"]),
    ]
    if has_stats:
        parts.append(pic("stats.svg", stats_alt))
    parts += [
        pic("achievements.svg", d["ach_alt"]),
        pic("inventory.svg", d["inv_alt"]),
        pic("quests-title.svg", d["quests_title"]),
        quests,
        linked(links["portfolio"], pic("quests-more.svg", d["quest_more"])),
        pic("night.svg", d["night_alt"]),
        linked(f'mailto:{links["email"]}', pic("start.svg", d["start_alt"].format(email=links["email"]))),
    ]
    note = ("<!-- Archivo generado por gen/build.py: edita data/profile.json y vuelve a generarlo. -->"
            if lang == "es" else
            "<!-- Generated by gen/build.py: edit data/profile.json and rebuild. -->")
    out = note + '\n<div align="center">\n\n' + "\n\n".join(parts) + "\n\n</div>\n"
    return bust_cache(out)


def bust_cache(text):
    """Añade ?v=<huella del archivo> a cada imagen: si el SVG cambia, cambia la URL y nadie ve una versión vieja."""
    def add(m):
        path = ROOT / m.group(2)
        v = hashlib.sha1(path.read_bytes()).hexdigest()[:8] if path.exists() else "0"
        return f"{m.group(1)}{m.group(2)}?v={v}"
    return re.sub(r"(https://github\.com/[^/]+/[^/]+/raw/main/)(assets/[^\"?]+\.svg)", add, text)
